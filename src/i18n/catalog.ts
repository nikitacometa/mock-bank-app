export const TRANSLATIONS: Readonly<
  Record<AppLocale, Readonly<Record<TranslationKey, string>>>
> = {
  ru: RU_MESSAGES,
  en: EN_MESSAGES,
};

export type TranslationParams = Readonly<Record<string, string | number>>;

export function isAppLocale(value: unknown): value is AppLocale {
  return typeof value === 'string' && (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

export function translate(
  locale: AppLocale,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  const messages = TRANSLATIONS[locale];
  const candidate: unknown = Object.hasOwn(messages, key) ? messages[key] : undefined;
  const template = typeof candidate === 'string' ? candidate : String(key);
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (placeholder, name: string) => {
    const replacement = params[name];
    return replacement === undefined ? placeholder : String(replacement);
  });
}

export function currencyName(locale: AppLocale, currency: Currency): string {
  return translate(locale, `currency.${currency}`);
}
